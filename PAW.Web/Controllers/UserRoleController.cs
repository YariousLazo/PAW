using Microsoft.AspNetCore.Mvc;
using PAW.Models.DTO;
using PAW.Web.Models;
using PAW.Web.Services;

namespace PAW.Web.Controllers
{
    public class UserRoleController : Controller
    {
        private readonly IUserRoleService _service;
        private readonly ILogger<UserRoleController> _logger;

        public UserRoleController(IUserRoleService service, ILogger<UserRoleController> logger)
        {
            _service = service;
            _logger = logger;
        }

        public async Task<IActionResult> Index(int page = 1)
        {
            var result = await _service.GetUserRolesAsync();
            return View(PagedList<UserRoleDTO>.Create(result, page));
        }

        [HttpGet]
        public async Task<IActionResult> Details(int id)
        {
            var dto = await _service.GetByIdAsync(id);
            return dto is null ? NotFound() : PartialView("_Details", dto);
        }

        [HttpGet]
        public IActionResult Create()
        {
            ViewData["IsNew"] = true;
            return PartialView("_Form", new UserRoleDTO());
        }

        [HttpGet]
        public async Task<IActionResult> Edit(int id)
        {
            var dto = await _service.GetByIdAsync(id);
            if (dto is null) return NotFound();
            ViewData["IsNew"] = false;
            return PartialView("_Form", dto);
        }

        // Creates or updates (the API decides). On validation errors the form partial is returned again.
        [HttpPost]
        public async Task<IActionResult> Save(UserRoleDTO dto, bool isNew)
        {
            // The Id is typed by the user when adding (it is not generated by the database).
            ViewData["IsNew"] = isNew;

            if (!ModelState.IsValid)
                return PartialView("_Form", dto);

            try
            {
                if (isNew && await _service.GetByIdAsync((int)dto.Id) is not null)
                {
                    ModelState.AddModelError(nameof(dto.Id), "An item with this ID already exists.");
                    return PartialView("_Form", dto);
                }

                if (!await _service.SaveAsync(dto))
                {
                    ModelState.AddModelError(string.Empty, "The user role could not be saved.");
                    return PartialView("_Form", dto);
                }

                return Json(new { success = true });
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Could not save the user role");
                ModelState.AddModelError(string.Empty, "The user role could not be saved. Make sure PAW.API is running.");
                return PartialView("_Form", dto);
            }
        }

        [HttpGet]
        public async Task<IActionResult> Delete(int id)
        {
            var dto = await _service.GetByIdAsync(id);
            return dto is null
                ? NotFound()
                : PartialView("_DeleteConfirm", new DeleteConfirmModel("User Role", id, $"user role #{dto.Id}"));
        }

        [HttpPost, ActionName("Delete")]
        public async Task<IActionResult> DeleteConfirmed(int id)
        {
            try
            {
                if (await _service.DeleteAsync(id))
                    return Json(new { success = true });

                ModelState.AddModelError(string.Empty, "The user role could not be deleted.");
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Could not delete the user role {Id}", id);
                ModelState.AddModelError(string.Empty, "The user role could not be deleted. It may be in use or the API is not running.");
            }

            return PartialView("_DeleteConfirm", new DeleteConfirmModel("User Role", id, "user role #" + id));
        }
    }
}
