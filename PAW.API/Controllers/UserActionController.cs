using Microsoft.AspNetCore.Mvc;
using PAW.DataAccess.Repositories;
using PAW.Models.DTO;

namespace PAW.API.Controllers
{
    [ApiController]
    [Route("[controller]")]
    public class UserActionController(ILogger<UserActionController> logger, IUserActionRepository userActionRepository) : ControllerBase
    {
        [HttpGet(Name = "GetUserActions")]
        public async Task<IEnumerable<UserActionDTO>> GetAll()
        {
            var items = await userActionRepository.ReadAsync() ?? [];
            return items.Select(UserActionDTO.ConvertFrom);
        }

        [HttpGet("{id:int}", Name = "GetUserActionById")]
        public async Task<ActionResult<UserActionDTO>> GetById(int id)
        {
            // Id is numeric(18,0) (decimal), so DbSet.Find(int) cannot be used here.
            var item = (await userActionRepository.ReadAsync()).FirstOrDefault(x => x.Id == id);
            if (item is null) return NotFound();
            return UserActionDTO.ConvertFrom(item);
        }

        [HttpPost]
        public async Task<ActionResult<bool>> Save([FromBody] UserActionDTO dto)
        {
            // The Id is supplied by the caller (it is not generated by the database):
            // update when it already exists, otherwise create.
            var existing = (await userActionRepository.ReadAsync()).FirstOrDefault(x => x.Id == dto.Id);
            if (existing is not null)
            {
                UserActionDTO.CopyTo(dto, existing);
                return await userActionRepository.UpdateAsync(existing);
            }

            return await userActionRepository.CreateAsync(UserActionDTO.ConvertTo(dto));
        }

        [HttpDelete("{id:int}")]
        public async Task<ActionResult<bool>> Delete(int id)
        {
            var item = (await userActionRepository.ReadAsync()).FirstOrDefault(x => x.Id == id);
            if (item is null) return NotFound();
            return await userActionRepository.DeleteAsync(item);
        }
    }
}
