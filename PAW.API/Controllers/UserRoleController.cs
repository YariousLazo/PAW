using Microsoft.AspNetCore.Mvc;
using PAW.DataAccess.Repositories;
using PAW.Models.DTO;

namespace PAW.API.Controllers
{
    [ApiController]
    [Route("[controller]")]
    public class UserRoleController(ILogger<UserRoleController> logger, IUserRoleRepository userRoleRepository) : ControllerBase
    {
        [HttpGet(Name = "GetUserRoles")]
        public async Task<IEnumerable<UserRoleDTO>> GetAll()
        {
            var items = await userRoleRepository.ReadAsync() ?? [];
            return items.Select(UserRoleDTO.ConvertFrom);
        }

        [HttpGet("{id:int}", Name = "GetUserRoleById")]
        public async Task<ActionResult<UserRoleDTO>> GetById(int id)
        {
            // Id is numeric(18,0) (decimal), so DbSet.Find(int) cannot be used here.
            var item = (await userRoleRepository.ReadAsync()).FirstOrDefault(x => x.Id == id);
            if (item is null) return NotFound();
            return UserRoleDTO.ConvertFrom(item);
        }

        [HttpPost]
        public async Task<ActionResult<bool>> Save([FromBody] UserRoleDTO dto)
        {
            // The Id is supplied by the caller (it is not generated by the database):
            // update when it already exists, otherwise create.
            var existing = (await userRoleRepository.ReadAsync()).FirstOrDefault(x => x.Id == dto.Id);
            if (existing is not null)
            {
                UserRoleDTO.CopyTo(dto, existing);
                return await userRoleRepository.UpdateAsync(existing);
            }

            return await userRoleRepository.CreateAsync(UserRoleDTO.ConvertTo(dto));
        }

        [HttpDelete("{id:int}")]
        public async Task<ActionResult<bool>> Delete(int id)
        {
            var item = (await userRoleRepository.ReadAsync()).FirstOrDefault(x => x.Id == id);
            if (item is null) return NotFound();
            return await userRoleRepository.DeleteAsync(item);
        }
    }
}
